"""Remotion project generator (v0).

Scaffolds a runnable, code-driven Remotion project from a Timeline. AGENT-4 owns
expanding the template gallery (kinetic typography, lower-thirds, 3D scenes…).
"""

from __future__ import annotations

import json
import os
from typing import Any

from .timeline import Timeline, to_remotion_props

_PACKAGE_JSON = {
    "name": "cineforge-remotion",
    "private": True,
    "scripts": {"render": "remotion render"},
    "dependencies": {
        "@remotion/cli": "^4.0.0",
        "react": "^18.3.0",
        "react-dom": "^18.3.0",
        "remotion": "^4.0.0",
    },
}

_COMPOSITION_TSX = """import {AbsoluteFill, Audio, Series, useCurrentFrame, interpolate, staticFile} from 'remotion';

export type Scene = {
  id: string;
  kind: string;
  fromFrame: number;
  durationInFrames: number;
  text?: string | null;
  color?: string | null;
  assetPath?: string | null;
  fontSize?: number | null;
};

export type Props = {
  fps: number;
  width: number;
  height: number;
  background: string;
  scenes: Scene[];
  audio: {id: string; assetPath?: string | null; volume: number; fromFrame: number; durationInFrames: number}[];
  durationInFrames: number;
};

const SceneView: React.FC<{scene: Scene}> = ({scene}) => {
  const frame = useCurrentFrame();
  const opacity = interpolate(frame, [0, 8, scene.durationInFrames - 8, scene.durationInFrames], [0, 1, 1, 0], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });
  return (
    <AbsoluteFill style={{backgroundColor: scene.color ?? '#101623', opacity}}>
      {scene.text ? (
        <div
          style={{
            fontFamily: 'Space Grotesk, Inter, sans-serif',
            fontSize: scene.fontSize ?? 120,
            fontWeight: 700,
            color: '#F5A524',
            letterSpacing: '-0.02em',
            textAlign: 'center',
            width: '100%',
          }}
        >
          {scene.text}
        </div>
      ) : null}
      {scene.assetPath ? (
        <img src={staticFile(scene.assetPath)} style={{width: '100%', height: '100%', objectFit: 'cover'}} />
      ) : null}
    </AbsoluteFill>
  );
};

export const CinematicComposition: React.FC<Props> = (props) => {
  return (
    <AbsoluteFill style={{backgroundColor: props.background}}>
      <Series>
        {props.scenes.map((scene) => (
          <Series.Sequence key={scene.id} durationInFrames={scene.durationInFrames}>
            <SceneView scene={scene} />
          </Series.Sequence>
        ))}
      </Series>
      {props.audio.map((a) =>
        a.assetPath ? (
          <Audio key={a.id} src={staticFile(a.assetPath)} volume={a.volume} />
        ) : null,
      )}
    </AbsoluteFill>
  );
};
"""

_INDEX_TS = """import {registerRoot, Composition} from 'remotion';
import {CinematicComposition, type Props} from './CinematicComposition';
import props from './props.json';

const root: React.FC = () => (
  <Composition
    id="Cinematic"
    component={CinematicComposition}
    defaultProps={props as unknown as Props}
    durationInFrames={(props as unknown as Props).durationInFrames}
    fps={(props as unknown as Props).fps}
    width={(props as unknown as Props).width}
    height={(props as unknown as Props).height}
  />
);

registerRoot(root);
"""


def generate_remotion_project(timeline: Timeline, project_dir: str) -> dict[str, Any]:
    """Write a runnable Remotion project. Returns a manifest describing it."""
    os.makedirs(os.path.join(project_dir, "src"), exist_ok=True)
    props = to_remotion_props(timeline)
    files = {
        "package.json": json.dumps(_PACKAGE_JSON, indent=2),
        "tsconfig.json": json.dumps({
            "compilerOptions": {
                "target": "ES2018", "module": "ESNext", "moduleResolution": "node",
                "jsx": "react-jsx", "strict": True, "skipLibCheck": True, "esModuleInterop": True,
            },
            "include": ["src"],
        }, indent=2),
        "src/CinematicComposition.tsx": _COMPOSITION_TSX,
        "src/index.ts": _INDEX_TS,
        "src/props.json": json.dumps(props, indent=2),
        "README.md": "# CINEFORGE Remotion project\n\nGenerated by video_engine.remotion_gen.\n\n"
                     "Render: `npm install && npx remotion render src/index.ts Cinematic out/render.mp4`\n",
    }
    for rel, content in files.items():
        path = os.path.join(project_dir, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
    return {
        "project_dir": project_dir,
        "files": list(files.keys()),
        "composition": "Cinematic",
        "props": props,
        "render_command": "npx remotion render src/index.ts Cinematic out/render.mp4",
    }
